/**
 * A Vite plugin that writes `sw.js`, the service worker that lets the app
 * open without a connection once it has been opened online.
 *
 * The worker's code is {@link serviceWorkerSource}. The build fills in the
 * list of files to keep (every file it wrote, apart from source maps, the
 * list of published PMOs and the Zenodo sign-in page) and a version made from
 * their contents, so each deploy gets a cache of its own.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

import type { Plugin } from "vite";

/** Files the worker does not keep: maps, data that changes daily, and pages that need a connection. */
export function isPrecached(path: string): boolean {
  return !(
    path.endsWith(".map") ||
    path === "sw.js" ||
    path.startsWith("repository/") ||
    path.startsWith("zenodo-callback.")
  );
}

/** Every file under `directory`, as paths relative to it with forward slashes, sorted. */
export function listFiles(directory: string): string[] {
  const files: string[] = [];
  const walk = (folder: string): void => {
    for (const name of readdirSync(folder)) {
      const path = join(folder, name);
      if (statSync(path).isDirectory()) walk(path);
      else files.push(relative(directory, path).split(sep).join("/"));
    }
  };
  walk(directory);
  return files.toSorted();
}

/**
 * The worker's code for one build.
 *
 * - Opening the app (`./` or `index.html`) tries the network first, with a
 *   short wait, and falls back to the kept copy. So an update arrives as soon
 *   as it is online, and the app still opens offline.
 * - The list of published PMOs tries the network first and keeps the last
 *   copy it got, for offline use.
 * - Every other kept file comes from the cache, then the network.
 * - Requests to other sites are left alone.
 *
 * A new worker waits until no tab uses the old one, so an open tab keeps a
 * matching set of files across a deploy.
 */
export function serviceWorkerSource(version: string, files: readonly string[]): string {
  return `// Generated by vite/serviceWorker.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const APP = "pmo-builder-app-" + VERSION;
const DATA = "pmo-builder-data";
const scope = self.registration.scope;
const kept = new Set(FILES.map((file) => new URL(file, scope).href));
const shell = new URL("index.html", scope).href;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(APP).then((cache) => cache.addAll([...kept])));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((name) => name.startsWith("pmo-builder-app-") && name !== APP)
            .map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

function withTimeout(promise, milliseconds) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error("timeout")), milliseconds);
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error);
      },
    );
  });
}

async function openApp(request) {
  try {
    const response = await withTimeout(fetch(request), 4000);
    if (response.ok) return response;
  } catch {
    // Offline or slow: use the kept copy.
  }
  return (await caches.match(shell, { cacheName: APP, ignoreVary: true })) || fetch(request);
}

async function latestData(request) {
  const cache = await caches.open(DATA);
  try {
    const response = await fetch(request);
    if (response.ok) await cache.put(request, response.clone());
    return response;
  } catch (error) {
    const copy = await cache.match(request, { ignoreVary: true });
    if (copy) return copy;
    throw error;
  }
}

async function keptFile(request) {
  // Module scripts are requested with an Origin header, and servers often
  // answer with "Vary: Origin", which would make the kept copy never match.
  const copy = await caches.match(request, { cacheName: APP, ignoreVary: true });
  return copy || fetch(request);
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.href.startsWith(scope)) return;
  const path = url.href.slice(scope.length).split(/[?#]/)[0];
  if (request.mode === "navigate" && (path === "" || path === "index.html")) {
    event.respondWith(openApp(request));
  } else if (path.startsWith("repository/")) {
    event.respondWith(latestData(request));
  } else if (kept.has(url.origin + url.pathname)) {
    event.respondWith(keptFile(request));
  }
});
`;
}

/** Writes `sw.js` into the build output. Does nothing for the dev server. */
export function serviceWorker(): Plugin {
  let outDir = "dist";
  return {
    name: "pmo-builder:service-worker",
    apply: "build",
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      const files = listFiles(outDir).filter(isPrecached);
      const hash = createHash("sha256");
      for (const file of files) {
        hash.update(file);
        hash.update(readFileSync(join(outDir, file)));
      }
      const version = hash.digest("hex").slice(0, 16);
      writeFileSync(join(outDir, "sw.js"), serviceWorkerSource(version, files));
    },
  };
}
